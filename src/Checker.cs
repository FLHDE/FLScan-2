using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using FLScanIE.Logging;
using FLScanIE.Util_Functions;

namespace FLScanIE
{
    [Flags]
    public enum Checks
    {
        None = 0,
        Audio = 1,
        Character = 2,
        Equipment = 4,
        Fonts = 8,
        Fx = 16,
        Loadouts = 32,
        Missions = 64,
        PetalDb = 128,
        Ship = 256,
        Solar = 512,
        Universe = 1024
    }

    public static class Checker
    {
        public static Checks Checks;
        public static FLDataFile flIni;
        public static string flDataPath;
        private static bool disableUTF;
        private static bool assumeVanillaFilesExist;
        private static HashSet<string> vanillaFiles;
        // Stripped-down copies of the vanilla INIs (only the settings the parse stage reads), by lowercase path
        // relative to DATA. Generated by tools\generate_vanilla_data.py.
        private static Dictionary<string, string> vanillaInis;
        // Hardpoint names of the vanilla models, by lowercase path relative to DATA
        private static Dictionary<string, string[]> vanillaHardpoints;

        public static FLDataFile confIni;

        public static bool DisableUTF
        {
            get { return disableUTF; }
            set { disableUTF = Properties.Settings.Default.setDisableUTF = value; }
        }

        public static bool AssumeVanillaFilesExist
        {
            get { return assumeVanillaFilesExist; }
            set { assumeVanillaFilesExist = Properties.Settings.Default.setAssumeVanillaFilesExist = value; }
        }

        static Checker()
        {
            confIni = new FLDataFile(GetAppFilePath("conf.ini"), false);
        }

        /// <summary>
        /// Returns the path of a file that is shipped next to the executable, independent of the working directory.
        /// </summary>
        private static string GetAppFilePath(string fileName)
        {
            return Path.Combine(AppDomain.CurrentDomain.BaseDirectory, fileName);
        }

        public static bool Parse(string flPath)
        {
            if (assumeVanillaFilesExist && !ParseVanillaFiles())
                return false;

            FLDataFile.ResetReportedEmptyFiles();
            string flExePath = Path.Combine(flPath, "EXE");
            try
            {
                flIni = new FLDataFile(flExePath + Path.DirectorySeparatorChar + "Freelancer.ini", true);
            }
            catch (Exception ex)
            {
                Logger.ELog("Error '" + ex.Message + "' when parsing '" + flExePath);
                return false;
            }
            flDataPath = Path.GetFullPath(Path.Combine(flExePath, flIni.GetSetting("Freelancer", "data path").Str(0)));

            // Every [Data] entry is a file relative to DATA. The parse stage skips missing ones, so report them here.
            foreach (var setting in flIni.GetSettings("Data"))
            {
                if (setting.NumValues() > 0 && !FileExists(setting.Str(0)))
                    Logger.LogFileNotFound("EXE\\freelancer.ini", setting);
            }

            try
            {
                CharacterChecks.ParseCharacterFolder();
                PetalDbChecks.ParsePetalDb();
                AudioChecks.ParseAudioFolder();
                FXChecks.ParseFXFolder();
                ShipChecks.ParseShipFolder();
                LoadoutChecks.ParseLoadouts();
                SolarChecks.ParseSolarFolder();
                Infocards.Load();
                EquipmentChecks.ParseEquipmentFolder();
                UniverseChecks.ParseUniverseFolder();
                FontChecks.ParseFontFoler();
            }
            catch (Exception ex)
            {
                Logger.ELog("An error happend while parsing. The scan can't continue. '" + ex.Message + "'" + ex.StackTrace);
                return false;
            }
            return true;
        }

        public static void Check()
        {
            if (ShouldCheck(Checks.Character))
                Util.RunCheck(CharacterChecks.CheckCharacterFolder, "characters");
            if (ShouldCheck(Checks.Universe))
                Util.RunCheck(UniverseChecks.CheckUniverseFolder, "universe");
            if (ShouldCheck(Checks.Audio))
                Util.RunCheck(AudioChecks.CheckAudioFolder, "audio");
            if (ShouldCheck(Checks.Fx))
                Util.RunCheck(FXChecks.CheckFX, "fx");
            if (ShouldCheck(Checks.Loadouts))
                Util.RunCheck(LoadoutChecks.CheckLoadouts, "loadouts");
            if (ShouldCheck(Checks.Solar))
                Util.RunCheck(SolarChecks.CheckSolarFolder, "solar");
            if (ShouldCheck(Checks.Ship))
                Util.RunCheck(ShipChecks.CheckShipFolder, "ships");
            if (ShouldCheck(Checks.Equipment))
                Util.RunCheck(EquipmentChecks.CheckEquipmentFolder, "equip");
            if (ShouldCheck(Checks.Missions))
            {
                Util.RunCheck(MissionChecks.CheckForMissingFormations, "missions");
                Util.RunCheck(MissionFileChecks.CheckMissionFiles, "mission files");
            }
            if (ShouldCheck(Checks.Fonts))
                Util.RunCheck(FontChecks.CheckFontFolder, "fonts");
        }

        private static bool ShouldCheck(Checks check)
        {
            return (Checks & check) != Checks.None;
        }

        private static bool ParseVanillaFiles()
        {
            string vanillaFilesPath = GetAppFilePath("vanilla_files.txt");
            if (!File.Exists(vanillaFilesPath))
            {
                Logger.ELog("Vanilla file list not found: " + vanillaFilesPath);
                return false;
            }

            vanillaFiles = new HashSet<string>();

            string[] files = File.ReadAllLines(vanillaFilesPath);
            foreach (string file in files)
            {
                vanillaFiles.Add(file.Trim().ToLowerInvariant());
            }

            return ParseVanillaInis() && ParseVanillaHardpoints();
        }

        private static bool ParseVanillaInis()
        {
            string path = GetAppFilePath("vanilla_inis.txt");
            if (!File.Exists(path))
            {
                Logger.ELog("Vanilla definitions not found: " + path);
                return false;
            }

            vanillaInis = new Dictionary<string, string>();
            string currentFile = null;
            var contents = new StringBuilder();
            foreach (string line in File.ReadAllLines(path, Encoding.GetEncoding("ISO-8859-1")))
            {
                if (line.StartsWith("@@ "))
                {
                    if (currentFile != null)
                        vanillaInis[currentFile] = contents.ToString();
                    currentFile = line.Substring(3).Trim().ToLowerInvariant();
                    contents.Length = 0;
                }
                else
                    contents.AppendLine(line);
            }
            if (currentFile != null)
                vanillaInis[currentFile] = contents.ToString();
            return true;
        }

        private static bool ParseVanillaHardpoints()
        {
            string path = GetAppFilePath("vanilla_hardpoints.txt");
            if (!File.Exists(path))
            {
                Logger.ELog("Vanilla hardpoint list not found: " + path);
                return false;
            }

            vanillaHardpoints = new Dictionary<string, string[]>();
            foreach (string line in File.ReadAllLines(path, Encoding.GetEncoding("ISO-8859-1")))
            {
                string[] parts = line.Split('\t');
                if (parts[0].Length != 0)
                    vanillaHardpoints[parts[0].ToLowerInvariant()] = parts.Skip(1).ToArray();
            }
            return true;
        }

        /// <summary>
        /// Converts a path that may be absolute or start with a separator into a lowercase path relative to DATA.
        /// </summary>
        private static string ToDataRelative(string path)
        {
            path = path.ToLowerInvariant();
            string dataPath = flDataPath.ToLowerInvariant();
            if (path.StartsWith(dataPath))
                path = path.Substring(dataPath.Length);
            path = path.Replace('/', '\\');
            // Repeated separators are allowed, like Windows does (vanilla mission scripts use them)
            while (path.Contains("\\\\"))
                path = path.Replace("\\\\", "\\");
            return path.TrimStart('\\');
        }

        /// <summary>
        /// Loads an INI file relative to DATA for the parse stage. If a vanilla file isn't present, the stripped-down
        /// vanilla copy is returned (<see cref="FLDataFile.IsVanillaCopy"/>), which only contains the settings the
        /// parse stage reads. Returns null if the file doesn't exist; that has to be reported by the caller.
        /// </summary>
        public static FLDataFile LoadIni(string relFilePath, bool multiFields = true)
        {
            if (FileExistsOnDisk(relFilePath))
                return new FLDataFile(Path.Combine(flDataPath, relFilePath), multiFields);

            string contents;
            if (!assumeVanillaFilesExist || !vanillaInis.TryGetValue(ToDataRelative(relFilePath), out contents))
                return null;

            var ini = new FLDataFile(Encoding.GetEncoding("ISO-8859-1").GetBytes(contents), relFilePath, multiFields);
            ini.IsVanillaCopy = true;
            // Line numbers of the copy are meaningless, and vanilla INIs are binary, so they don't have any
            foreach (var setting in ini.sections.SelectMany(s => s.settings))
                setting.LineNumber = 0;
            return ini;
        }

        /// <summary>
        /// Returns the hardpoint names of a vanilla model that isn't present, or null if they aren't known.
        /// </summary>
        public static string[] GetVanillaHardpoints(string relFilePath)
        {
            string[] hardpoints;
            if (assumeVanillaFilesExist && vanillaHardpoints.TryGetValue(ToDataRelative(relFilePath), out hardpoints))
                return hardpoints;
            return null;
        }

        /// <summary>
        /// True if the file (relative to the DATA folder) is physically present. Unlike <see cref="FileExists"/>,
        /// this doesn't count vanilla files that are only assumed to exist, so use it before opening a file.
        /// </summary>
        public static bool FileExistsOnDisk(string relFilePath)
        {
            try
            {
                return File.Exists(Path.Combine(flDataPath, relFilePath));
            }
            catch (ArgumentException)
            {
                // The path contains invalid characters, so it can't exist
                return false;
            }
        }

        public static bool FileExists(string relFilePath)
        {
            return FileExistsOnDisk(relFilePath) || HasVanillaFile(relFilePath);
        }

        internal static bool HasVanillaFile(string relFilePath)
        {
            if (!assumeVanillaFilesExist)
                return false;
            return vanillaFiles.Contains(ToDataRelative(relFilePath));
        }
    }
}
